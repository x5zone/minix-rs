/// The full normal (unescaped) table, implementing [`KeyMap`].
pub struct FullMap;

impl KeyMap for FullMap {
    fn normal(&self, index: u8) -> KeyCode {
        let (page, code) = SCANMAP_NORMAL[index as usize];
        KeyCode { page, code }
    }

    fn escaped(&self, index: u8) -> KeyCode {
        let (page, code) = SCANMAP_ESCAPED[index as usize];
        KeyCode { page, code }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::scancode::{PAGE_KEY, KEY_ENTER, KEY_ESCAPE};

    #[test]
    fn test_full_map_spots_match_c_entries() {
        let map = FullMap;
        // Spot checks against table.c entries.
        let esc = map.normal(0x01);
        assert_eq!((esc.page, esc.code), (PAGE_KEY, KEY_ESCAPE));
        let enter = map.normal(0x1C);
        assert_eq!((enter.page, enter.code), (PAGE_KEY, KEY_ENTER));
        // Q at 0x10: HID keyboard Q is 0x14.
        let q = map.normal(0x10);
        assert_eq!(q.code, 0x14);
        // Escaped KP Enter at 0x1C.
        let kp_enter = map.escaped(0x1C);
        assert_eq!(kp_enter.code, 0x58);
    }

    #[test]
    fn test_full_map_covers_populated_entries() {
        // Entry counts: 111 normal + 40 escaped populated in C table.c.
        assert_eq!(SCANMAP_NORMAL.iter().filter(|e| e.0 != 0).count(), 111);
        assert_eq!(SCANMAP_ESCAPED.iter().filter(|e| e.0 != 0).count(), 40);
    }

    #[test]
    fn test_padding_swallows() {
        let map = FullMap;
        let none = map.normal(0x00); // unmapped slot
        assert_eq!((none.page, none.code), (0, 0));
    }
}
