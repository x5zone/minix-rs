//! Full scancode tables: PC keyboard scan codes to USB HID usage codes.
//!
//! C correspondence: `minix3/minix/drivers/hid/pckbd/table.c` (169
//! lines) — `scanmap_normal` and `scanmap_escaped`, both indexed by the
//! seven-bit scan code (release bit stripped). Each entry is
//! `(page, code)`; `(0, 0)` is padding and swallows the key. Values were
//! extracted mechanically from `minix3/minix/include/minix/input.h`
//! (USB HID usage enum) so the tables are data, byte-for-byte C parity.
//!
//! Full-map behavior: a lookup that hits padding produces no event.

