/// In-place extractor using the same criteria as the manifest (literal regex,
/// recomputable by tooling).
fn gated_test_names(src: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut parts = src.split("#[test]").peekable();
    parts.next(); // the first segment holds no content after any #[test]
    while let Some(seg) = parts.next() {
        // the next `fn NAME` after #[test]
        if let Some(rest) = seg
            .lines()
            .map(str::trim)
            .skip_while(|l| l.starts_with("//") || l.is_empty())
            .find(|l| l.starts_with("fn "))
            .map(|l| l.to_string())
        {
            let name = rest
                .trim_start_matches("fn ")
                .split(|c: char| !(c.is_alphanumeric() || c == '_'))
                .next()
                .unwrap_or("")
                .to_string();
            out.push(name);
        }
        let _ = parts.peek();
    }
    out
}

fn read_src(rel: &str) -> String {
    // This file lives in os/arch/tests/; the manifest keys are relative to os/.
    let path = format!("../{rel}");
    std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("读 {path} 失败：{e}（清单键漂移？）"))
}

#[test]
fn gated_test_inventory_matches_frozen_manifest() {
    let mut failures = Vec::new();
    for (rel, frozen) in FROZEN {
        let live = gated_test_names(&read_src(rel));
        let frozen: Vec<String> = frozen.iter().map(|s| s.to_string()).collect();
        if live != frozen {
            let added: Vec<_> = live
                .iter()
                .filter(|n| !frozen.contains(n))
                .cloned()
                .collect();
            let removed: Vec<_> = frozen
                .iter()
                .filter(|n| !live.contains(n))
                .cloned()
                .collect();
            failures.push(format!(
                "{rel}: 新增 {added:?}，删除 {removed:?}——门内测试集合变动必须给出宿主可达化去向或豁免理由（P-ALL-01）"
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "架构门内测试清单漂移：\n{}",
        failures.join("\n")
    );
}

#[test]
fn frozen_manifest_total_is_known() {
    // Total-count sentinel: 86 (frozen 2026-10-06). If someone adds a gated
    // test and forgets the manifest, the previous test reports the per-file
    // difference; if someone renames a whole file so the read fails, the
    // previous test panics; this one backstops the manifest key count itself.
    let files: usize = FROZEN.len();
    let tests: usize = FROZEN.iter().map(|(_, v)| v.len()).sum();
    assert_eq!(files, 20, "受审计文件数");
    assert_eq!(tests, 86, "受审计门内测试总数（2026-10-06 冻结值）");
}
