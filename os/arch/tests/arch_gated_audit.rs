//! Frozen-manifest audit of architecture-gated `#[test]`s (the host-runnable
//! per-architecture static source audit chosen for the gated-test inventory).
//!
//! The modules under `os/arch/src/{arm64,riscv64}` and
//! `os/plat/src/{arm64,riscv64}` are gated wholesale behind
//! `#[cfg(target_arch = …)]`, so the host (x86_64) `cargo test` never
//! compiles them — the 86 `#[test]`s inside the gates never run yet report
//! green (a reachability-discipline trap this project has hit twice). This
//! audit turns the "invisible unknown set" into a "frozen known set that goes
//! red on drift":
//!
//! - A gated test being **added/removed/renamed** (relative to the manifest
//!   frozen in this file) ⇒ this audit fails, forcing the reviewer to look
//!   at that test's host-reachability path (include_str! shape pin, constant
//!   migration, or a registered exemption reason).
//! - Bulk removal of gated tests must also pass here — deleting a test is no
//!   longer a silent operation.
//!
//! Depth grading (which files have separate behavior/shape-level host
//! audits): `trap_return`/`trap_stub` have dedicated pin files for both
//! architectures (riscv64_return_leg_pin / riscv64_trap_leg_shape /
//! arm64_return_leg_pin / arm64_trap_leg_shape), and the paging encoding
//! bits for both architectures live in `paging_encoding_pins.rs`. The
//! remaining files are bounded by this manifest audit.

